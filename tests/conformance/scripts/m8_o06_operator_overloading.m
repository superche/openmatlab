% M8 O06 - operator and conversion overloading
% Thick conformance: writes class files into a temp folder on the path.
d = tempname; mkdir(d);
wcls_m8(d, 'VecO6', { ...
  'classdef VecO6', ...
  '  properties', ...
  '    v = []', ...
  '  end', ...
  '  methods', ...
  '    function obj = VecO6(v)', ...
  '      if nargin > 0', ...
  '        obj.v = v;', ...
  '      end', ...
  '    end', ...
  '    function r = plus(a, b)', ...
  '      r = VecO6(VecO6.raw(a) + VecO6.raw(b));', ...
  '    end', ...
  '    function r = minus(a, b)', ...
  '      r = VecO6(VecO6.raw(a) - VecO6.raw(b));', ...
  '    end', ...
  '    function r = mtimes(a, b)', ...
  '      r = VecO6(VecO6.raw(a) * VecO6.raw(b));', ...
  '    end', ...
  '    function r = uminus(a)', ...
  '      r = VecO6(-a.v);', ...
  '    end', ...
  '    function t = eq(a, b)', ...
  '      t = isequal(VecO6.raw(a), VecO6.raw(b));', ...
  '    end', ...
  '    function t = lt(a, b)', ...
  '      t = sum(VecO6.raw(a)) < sum(VecO6.raw(b));', ...
  '    end', ...
  '    function r = horzcat(varargin)', ...
  '      parts = cellfun(@VecO6.raw, varargin, ''UniformOutput'', false);', ...
  '      r = VecO6([parts{:}]);', ...
  '    end', ...
  '    function d = double(a)', ...
  '      d = a.v;', ...
  '    end', ...
  '    function s = char(a)', ...
  '      s = mat2str(a.v);', ...
  '    end', ...
  '    function n = length(a)', ...
  '      n = numel(a.v);', ...
  '    end', ...
  '  end', ...
  '  methods (Static)', ...
  '    function x = raw(a)', ...
  '      if isa(a, ''VecO6'')', ...
  '        x = a.v;', ...
  '      else', ...
  '        x = a;', ...
  '      end', ...
  '    end', ...
  '  end', ...
  'end', ...
});
addpath(d);
a = VecO6([1 2 3]);
b = VecO6([10 20 30]);
c = a + b;
f1 = c.v;
c2 = a + 1;
f2 = c2.v;
c3 = 1 + a;
f3 = c3.v;
m = 2 * a;
f4 = m.v;
n = -a;
f5 = n.v;
f6 = a == VecO6([1 2 3]);
f7 = a < b;
h = [a b];
f8 = h.v;
f9 = double(a);
f10 = strcmp(char(a), '[1 2 3]');
f11 = length(b);
dd = b - a;
f12 = dd.v;
pp = plus(a, b);
f13 = pp.v(2);
f14 = b < a;
rmpath(d);

function wcls_m8(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
