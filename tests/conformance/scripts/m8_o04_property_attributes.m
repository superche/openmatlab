% M8 O04 - property attributes, Constant, Dependent, set/get methods
% Thick conformance: writes class files into a temp folder on the path.
d = tempname; mkdir(d);
wcls_m8(d, 'TempO4', { ...
  'classdef TempO4', ...
  '  properties (Constant)', ...
  '    K0 = 273.15', ...
  '  end', ...
  '  properties', ...
  '    c = 0', ...
  '  end', ...
  '  properties (Dependent)', ...
  '    k', ...
  '  end', ...
  '  properties (SetAccess = private)', ...
  '    hist = 0', ...
  '  end', ...
  '  properties (Access = private)', ...
  '    secret = 7', ...
  '  end', ...
  '  methods', ...
  '    function obj = TempO4(c)', ...
  '      if nargin > 0', ...
  '        obj.c = c;', ...
  '      end', ...
  '    end', ...
  '    function v = get.k(obj)', ...
  '      v = obj.c + TempO4.K0;', ...
  '    end', ...
  '    function obj = set.k(obj, v)', ...
  '      obj.c = v - TempO4.K0;', ...
  '    end', ...
  '    function obj = set.c(obj, v)', ...
  '      if v < -273.15', ...
  '        error(''TempO4:range'', ''below absolute zero'');', ...
  '      end', ...
  '      obj.c = v;', ...
  '      obj.hist = obj.hist + 1;', ...
  '    end', ...
  '    function s = peek(obj)', ...
  '      s = obj.secret;', ...
  '    end', ...
  '  end', ...
  'end', ...
});
addpath(d);
t = TempO4(25);
d1 = t.k;
t.k = 300;
d2 = t.c;
d3 = TempO4.K0;
d4 = t.hist;
d5 = 0;
try
  t.hist = 5;
catch
  d5 = 1;
end
d6 = 0;
try
  v = t.secret;
catch
  d6 = 1;
end
d7 = peek(t);
d8 = 0;
try
  t.c = -300;
catch e
  d8 = strcmp(e.identifier, 'TempO4:range');
end
d9 = 0;
try
  t.K0 = 1;
catch
  d9 = 1;
end
d10 = t.K0;
d11 = t.c;
z = TempO4();
d12 = [z.c z.hist];
rmpath(d);

function wcls_m8(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
