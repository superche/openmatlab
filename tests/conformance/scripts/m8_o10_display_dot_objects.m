% M8 O10 - object display (default and disp overload) and dot notation on built-in objects
% Thick conformance: writes class files into a temp folder on the path.
d = tempname; mkdir(d);
wcls_m8(d, 'ShowO10', { ...
  'classdef ShowO10', ...
  '  properties', ...
  '    val = 3', ...
  '  end', ...
  '  methods', ...
  '    function disp(obj)', ...
  '      fprintf(''ShowO10<%d>\n'', obj.val);', ...
  '    end', ...
  '  end', ...
  'end', ...
});
wcls_m8(d, 'PlainO10', { ...
  'classdef PlainO10', ...
  '  properties', ...
  '    x = 1', ...
  '  end', ...
  'end', ...
});
addpath(d);
s = ShowO10;
t1 = evalc('s');
j1 = ~isempty(strfind(t1, 'ShowO10<3>'));
t2 = evalc('disp(s)');
j2 = strcmp(strtrim(t2), 'ShowO10<3>');
p = PlainO10;
t3 = evalc('p');
j3 = ~isempty(strfind(t3, 'PlainO10 with properties:'));
j4 = ~isempty(strfind(t3, 'x: 1'));
f = figure('Visible', 'off');
h = plot(1:3);
h.LineWidth = 3;
j5 = get(h, 'LineWidth');
j6 = h.LineWidth;
ax = gca;
ax.XLim = [0 5];
j7 = isequal(get(ax, 'XLim'), [0 5]);
j8 = strcmp(h.Type, 'line');
dt = datetime(2020, 5, 6);
j9 = [dt.Year dt.Month dt.Day];
close(f);
j10 = isvalid(h);
j11 = isobject(h);
rmpath(d);

function wcls_m8(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
