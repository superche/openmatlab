c10 = isequal(superclasses('CubeO3'), {'SqO3'; 'ShapeO3'});
c11 = k.side;
L = LogAccO3;
add(L, 4);
L.add(6);
c12 = [L.total L.count];
c13 = isa(L, 'handle');
c14 = isa(s, 'CubeO3');
rmpath(d);

function wcls_m8(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
