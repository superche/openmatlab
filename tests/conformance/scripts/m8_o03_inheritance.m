% M8 O03 - inheritance, superclass constructors, method@Super calls, dynamic dispatch
% Thick conformance: writes class files into a temp folder on the path.
d = tempname; mkdir(d);
wcls_m8(d, 'ShapeO3', { ...
  'classdef ShapeO3', ...
  '  properties', ...
  '    name = ''shape''', ...
  '  end', ...
  '  methods', ...
  '    function obj = ShapeO3(nm)', ...
  '      if nargin > 0', ...
  '        obj.name = nm;', ...
  '      end', ...
  '    end', ...
  '    function a = area(obj)', ...
  '      a = 0;', ...
  '    end', ...
  '    function s = describe(obj)', ...
  '      s = sprintf(''%s:%g'', obj.name, area(obj));', ...
  '    end', ...
  '  end', ...
  'end', ...
});
wcls_m8(d, 'SqO3', { ...
  'classdef SqO3 < ShapeO3', ...
  '  properties', ...
  '    side = 1', ...
  '  end', ...
  '  methods', ...
  '    function obj = SqO3(s)', ...
  '      obj@ShapeO3(''sq'');', ...
  '      obj.side = s;', ...
  '    end', ...
  '    function a = area(obj)', ...
  '      a = obj.side^2;', ...
  '    end', ...
  '  end', ...
  'end', ...
});
wcls_m8(d, 'CubeO3', { ...
  'classdef CubeO3 < SqO3', ...
  '  methods', ...
  '    function obj = CubeO3(s)', ...
  '      obj@SqO3(s);', ...
  '      obj.name = ''cube'';', ...
  '    end', ...
  '    function a = area(obj)', ...
  '      a = 6 * area@SqO3(obj);', ...
  '    end', ...
  '  end', ...
  'end', ...
});
wcls_m8(d, 'AccO3', { ...
  'classdef AccO3 < handle', ...
  '  properties', ...
  '    total = 0', ...
  '  end', ...
  '  methods', ...
  '    function add(obj, v)', ...
  '      obj.total = obj.total + v;', ...
  '    end', ...
  '  end', ...
  'end', ...
});
wcls_m8(d, 'LogAccO3', { ...
  'classdef LogAccO3 < AccO3', ...
