% M8 O07 - subsref/subsasgn overloads with builtin fallback
% Thick conformance: writes class files into a temp folder on the path.
d = tempname; mkdir(d);
wcls_m8(d, 'BoxO7', { ...
  'classdef BoxO7', ...
  '  properties', ...
  '    data = []', ...
  '  end', ...
  '  methods', ...
  '    function varargout = subsref(obj, s)', ...
  '      switch s(1).type', ...
  '        case ''()''', ...
  '          varargout{1} = obj.data(s(1).subs{:}) * 10;', ...
  '        case ''{}''', ...
  '          varargout{1} = obj.data(end - s(1).subs{1} + 1);', ...
  '        otherwise', ...
  '          if strcmp(s(1).subs, ''count'')', ...
  '            varargout{1} = numel(obj.data);', ...
  '          else', ...
  '            varargout{1} = builtin(''subsref'', obj, s);', ...
  '          end', ...
  '      end', ...
  '    end', ...
  '    function obj = subsasgn(obj, s, val)', ...
  '      if strcmp(s(1).type, ''()'')', ...
  '        obj.data(s(1).subs{:}) = val * 2;', ...
  '      else', ...
  '        obj = builtin(''subsasgn'', obj, s, val);', ...
  '      end', ...
  '    end', ...
  '  end', ...
  'end', ...
});
addpath(d);
b = BoxO7;
b.data = [1 2 3];
g1 = b(2);
g2 = b.count;
g3 = b{1};
b(2) = 5;
g4 = b.data(2);
g5 = b(2);
b.data(4) = 1;
g6 = b.count;
g7 = b.data;
g8 = b{2};
rmpath(d);

function wcls_m8(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
