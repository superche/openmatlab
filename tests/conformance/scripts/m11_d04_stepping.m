% M11 D04 - dbstep / dbstep in / dbstep out / dbcont with correct lines
% Paused-session commands come from m11_d04_stepping.queue.
d = tempname; mkdir(d);
wf_d04(d, 'step_d04', { ...
  'function y = step_d04(n)', ...
  '  y = 0;', ...
  '  for k = 1:n', ...
  '    y = y + helper_d04(k);', ...
  '  end', ...
  '  y = y * 10;', ...
  'end', ...
  'function h = helper_d04(k)', ...
  '  h = k * 2;', ...
  'end'});
addpath(d);
global TR_D04
TR_D04 = [];
dbstop in step_d04 at 2
y = step_d04(2);
dbclear all
p1 = TR_D04;
p2 = y;
p3 = isempty(dbstatus);
rmpath(d);

function wf_d04(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
