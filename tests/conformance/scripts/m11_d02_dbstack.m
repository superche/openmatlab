% M11 D02 - dbstack struct, printed form, -completenames, dbstack(n), mfilename
d = tempname; mkdir(d);
wf_d02(d, 'outer_d02', { ...
  'function r = outer_d02()', ...
  '  r = inner_d02();', ...
  'end', ...
  'function s = inner_d02()', ...
  '  s = dbstack;', ...
  'end'});
wf_d02(d, 'skip_d02', { ...
  'function r = skip_d02()', ...
  '  r = in_skip_d02();', ...
  'end', ...
  'function s = in_skip_d02()', ...
  '  s = dbstack(1);', ...
  'end'});
wf_d02(d, 'full_d02', { ...
  'function c = full_d02()', ...
  '  c = dbstack(''-completenames'');', ...
  'end'});
wf_d02(d, 'pr_d02', { ...
  'function pr_d02()', ...
  '  dbstack', ...
  'end'});
wf_d02(d, 'mf_d02', { ...
  'function m = mf_d02()', ...
  '  m = mfilename;', ...
  'end'});
addpath(d);
st = outer_d02();
b1 = double(numel(st) >= 2);
b2 = double(contains(st(1).name, 'inner_d02'));
b3 = st(1).line;
b4 = double(strcmp(st(2).name, 'outer_d02'));
b5 = st(2).line;
b6 = isequal(fieldnames(st)', {'file','name','line'});
b7 = double(strcmp(st(1).file, 'outer_d02.m'));
sk = skip_d02();
b8 = double(strcmp(sk(1).name, 'skip_d02'));
b9 = sk(1).line;
c = full_d02();
b10 = double(strcmp(c(1).file, fullfile(d, 'full_d02.m')));
out = evalc('pr_d02()');
b11 = double(contains(out, 'In pr_d02') && contains(out, 'line 2'));
b12 = double(strcmp(mf_d02(), 'mf_d02'));
rmpath(d);

function wf_d02(d, name, lines)
  fid = fopen(fullfile(d, [name '.m']), 'w');
  fprintf(fid, '%s\n', lines{:});
  fclose(fid);
end
